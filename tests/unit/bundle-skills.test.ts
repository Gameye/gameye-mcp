// scripts/bundle-skills.mjs turns a pinned gameye-skills checkout into the
// generated src/generated/skills.ts. It is pure (JSON in, TypeScript out), so
// the --check drift test in CI depends on it being byte-stable.
// Driven through node because the scripts are plain .mjs without types.

import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

const script = fileURLToPath(new URL("../../scripts/bundle-skills.mjs", import.meta.url));

interface BundleInput {
  tag: string;
  commit: string;
  files: Record<string, string>;
}

function bundle(input: BundleInput): string {
  return execFileSync(process.execPath, [script], { input: JSON.stringify(input), encoding: "utf8", stdio: ["pipe", "pipe", "pipe"] });
}

const skill = (name: string, version: string, body: string) =>
  `---\nname: ${name}\ndescription: The ${name} skill. Use it for ${name} things.\nmetadata:\n  version: "${version}"\n---\n\n${body}`;

const CONTAINERIZE = skill(
  "gameye-containerize",
  "1.2.0",
  `# Containerizing

## The container contract

1. **\`linux/amd64\` only.** The fleet is x86_64.
   Build with buildx.
2. **Bind fixed container ports on \`0.0.0.0\`.** Match the Admin Panel.
3. **Run as non-root.** Hygiene.

## Dockerfile pattern

1. Not a contract item.
`
);

const INPUT: BundleInput = {
  tag: "v1.6.1",
  commit: "b1927e7c6d2397cfbc87cbbb03d9ac128225b515",
  files: {
    "skills/gameye/SKILL.md": skill("gameye", "1.1.0", "# Gameye\n\nPack version: 1.6.1\n"),
    "skills/gameye/references/routing.md": "# Routing\n",
    "skills/gameye-containerize/SKILL.md": CONTAINERIZE,
    "skills/gameye-containerize/references/registries.md": "# Registries\n",
    "skills/gameye-web-server/SKILL.md": skill("gameye-web-server", "1.0.0", "# Web\n"),
  },
};

/** The same files, inserted in a different order. */
function shuffled(input: BundleInput): BundleInput {
  return { ...input, files: Object.fromEntries(Object.entries(input.files).reverse()) };
}

describe("bundle-skills", () => {
  it("is byte-stable for the same input, whatever the file order", () => {
    const once = bundle(INPUT);
    expect(bundle(INPUT)).toBe(once);
    expect(bundle(shuffled(INPUT))).toBe(once);
  });

  it("opens with a header naming pack version, tag, source commit, licence and do-not-edit", () => {
    const out = bundle(INPUT);
    const header = out.slice(0, out.indexOf("\n\n"));
    expect(header).toContain("Pack version: 1.6.1");
    expect(header).toContain("Tag: v1.6.1");
    expect(header).toContain("Source commit: b1927e7c6d2397cfbc87cbbb03d9ac128225b515");
    expect(header).toContain("MIT");
    expect(header).toContain("Copyright (c) 2026 Gameye B.V.");
    expect(header).toContain("Generated by scripts/sync-skills.mjs. Do not edit.");
  });

  it("exports the pack constants", () => {
    const out = bundle(INPUT);
    expect(out).toContain('export const BUNDLED_SKILLS_PACK_VERSION = "1.6.1";');
    expect(out).toContain('export const BUNDLED_SKILLS_TAG = "v1.6.1";');
    expect(out).toContain('export const BUNDLED_SKILLS_COMMIT = "b1927e7c6d2397cfbc87cbbb03d9ac128225b515";');
  });

  it("indexes every skill with its frontmatter, sorted by name, and keeps SKILL.md and reference text", () => {
    const out = bundle(INPUT);
    const names = [...out.matchAll(/^ {4}"name": "([^"]+)"/gm)].map((m) => m[1]);
    expect(names).toEqual(["gameye", "gameye-containerize", "gameye-web-server"]);
    expect(out).toContain('"description": "The gameye-containerize skill. Use it for gameye-containerize things."');
    expect(out).toContain('"version": "1.2.0"');
    expect(out).toContain('"references/registries.md": "# Registries\\n"');
    expect(out).toContain(JSON.stringify(INPUT.files["skills/gameye/SKILL.md"]));
  });

  it("extracts the numbered container contract items and nothing from later sections", () => {
    const out = bundle(INPUT);
    const start = out.indexOf("export const CONTAINER_CONTRACT");
    const block = out.slice(start, out.indexOf("];", start));
    expect(block).toContain('"number": 1');
    expect(block).toContain('"text": "**`linux/amd64` only.** The fleet is x86_64. Build with buildx."');
    expect(block).toContain('"number": 3');
    expect(block).toContain('"text": "**Run as non-root.** Hygiene."');
    expect(block).not.toContain('"number": 4');
    expect(block).not.toContain("Not a contract item");
  });

  it("leaves an empty templates index", () => {
    expect(bundle(INPUT)).toMatch(/export const BUNDLED_TEMPLATES: readonly BundledTemplate\[\] = \[\];/);
  });

  it("refuses input without a Pack version line", () => {
    const files = { ...INPUT.files, "skills/gameye/SKILL.md": skill("gameye", "1.1.0", "# Gameye\n") };
    expect(() => bundle({ ...INPUT, files })).toThrow();
  });

  it("refuses a skill whose frontmatter name differs from its directory", () => {
    const files = { ...INPUT.files, "skills/gameye-web-server/SKILL.md": skill("other", "1.0.0", "# Web\n") };
    expect(() => bundle({ ...INPUT, files })).toThrow();
  });

  it("refuses a containerize skill with no container contract items", () => {
    const files = { ...INPUT.files, "skills/gameye-containerize/SKILL.md": skill("gameye-containerize", "1.2.0", "# None\n") };
    expect(() => bundle({ ...INPUT, files })).toThrow();
  });
});
